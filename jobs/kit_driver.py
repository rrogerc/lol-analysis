def attack_block(slug):
    """attack.windupFraction and attack.ranged from Riot's character file. The
    windup is 30% plus the file's attack cast offset where it has one, and
    attack cast time over attack total time where it states those instead
    (older champions: Rakan 0.27 / 1.575; the two agree where the wiki gives
    both forms, Vex 0.25 / 1.6 = 0.3 - 0.14375)."""
    import builds
    champ = builds.load_champion(slug)
    riot = champ["riot"] or {}
    rng = riot.get("attackRange", champ["dd"]["stats"]["attackrange"])
    attack = {}
    try:
        with open(os.path.join(ks.source_dir(slug), "bin.json")) as f:
            record = next(v for v in json.load(f).values()
                          if isinstance(v, dict) and v.get("__type") == "CharacterRecord")
        attack = record.get("basicAttack") or {}
    except (SystemExit, OSError, StopIteration):
        pass
    if "attackDelayCastOffsetPercent" in riot:
        windup = 0.3 + riot["attackDelayCastOffsetPercent"]
    elif "mAttackDelayCastOffsetPercent" in attack:
        windup = 0.3 + attack["mAttackDelayCastOffsetPercent"]
    elif attack.get("mAttackCastTime") and attack.get("mAttackTotalTime"):
        windup = attack["mAttackCastTime"] / attack["mAttackTotalTime"]
    else:
        hand = os.path.join(BASE_DIR, "data", "builds", f"{slug}.json")
        if os.path.exists(hand):  # a snapshot from before riot.json: the hand kit states it
            with open(hand) as f:
                windup = json.load(f)["attack"]["windupFraction"]
        else:
            windup = 0.3  # the file states neither: no offset
    return {"windupFraction": round(windup, 5), "ranged": rng > 325}


def numbers_in(node, out):
    if isinstance(node, bool):
        return
    if isinstance(node, (int, float)):
        out.add(float(node))
    elif isinstance(node, str):
        for m in re.findall(r"(?<![\w.])-?\d+(?:\.\d+)?", node):
            out.add(float(m))
    elif isinstance(node, list):
        for v in node:
            numbers_in(v, out)
    elif isinstance(node, dict):
        for v in node.values():
            numbers_in(v, out)


def source_numbers(slug):
    """Every number the dossier, the numbers sheet or the wiki text states."""
    src = ks.load_sources(slug)
    with open(os.path.join(ks.DOSSIERS_DIR, f"{slug}.json")) as f:
        dossier = json.load(f)
    out = set()
    numbers_in(dossier, out)
    numbers_in(src["sheet"], out)
    numbers_in(src["wiki"], out)
    return out


