def ranks_of(xs):
    order = sorted(range(len(xs)), key=lambda i: xs[i])
    out, i = [0.0] * len(xs), 0
    while i < len(order):
        j = i
        while j + 1 < len(order) and xs[order[j + 1]] == xs[order[i]]:
            j += 1
        for k in range(i, j + 1):
            out[order[k]] = (i + j) / 2.0
        i = j + 1
    return out


def spearman(a, b):
    ra, rb = ranks_of(a), ranks_of(b)
    ma, mb = sum(ra) / len(ra), sum(rb) / len(rb)
    cov = sum((x - ma) * (y - mb) for x, y in zip(ra, rb))
    va, vb = sum((x - ma) ** 2 for x in ra), sum((y - mb) ** 2 for y in rb)
    return cov / math.sqrt(va * vb) if va and vb else float("nan")


def median(xs):
    xs = sorted(xs)
    return xs[len(xs) // 2] if xs else float("nan")


def cmd_compare(args):
    sys.path.insert(0, BASE_DIR)
    import builds
    slug, name = args.slug, f"{args.slug}_blind"
    hand, blind = Fights(builds.load_kit(slug), slug), Fights(builds.load_kit(name), slug)
    rng = random.Random(7)
    pool_ids = [i for i in builds.DEFAULT_POOL if i in hand.pool]
    sample = [[rng.choice(builds.BOOTS)] + rng.sample(pool_ids, 5) for _ in range(args.n)]
    report = {}
    for pname, (hp, ar, mr, dur) in PRESETS.items():
        rows = []
        for items in sample:
            a = hand.run(16, items, hp, ar, mr, dur)
            b = blind.run(16, items, hp, ar, mr, dur)
            score = lambda r: r["ttk"] if r["ttk"] is not None else dur * (1 + r["hp_left"] / hp)  # noqa: E731
            rows.append((a["total"], b["total"], a["ttk"], b["ttk"], score(a), score(b)))
        k = max(5, args.n // 10)
        top_a = set(sorted(range(len(rows)), key=lambda i: rows[i][4])[:k])
        top_b = set(sorted(range(len(rows)), key=lambda i: rows[i][5])[:k])
        both = [(r[2], r[3]) for r in rows if r[2] is not None and r[3] is not None]
        report[pname] = {
            "spearman": round(spearman([r[4] for r in rows], [r[5] for r in rows]), 3),
            f"top{k}Overlap": len(top_a & top_b),
            "bestBuildRankInBlind": sorted(range(len(rows)), key=lambda i: rows[i][5]).index(
                min(range(len(rows)), key=lambda i: rows[i][4])) + 1,
            "medianDamageRatio": round(median([r[1] / r[0] for r in rows if r[0] > 0]), 3),
            "kills": [sum(r[2] is not None for r in rows), sum(r[3] is not None for r in rows)],
            "medianKillTimeRatio": round(median([b / a for a, b in both]), 3) if both else None,
        }
    naked_a = hand.run(16, [], 30_000, 100, 100, 15.0)
    naked_b = blind.run(16, [], 30_000, 100, 100, 15.0)
    report["naked15s"] = {"hand": {k: round(v) for k, v in naked_a["breakdown"].items()},
                          "blind": {k: round(v) for k, v in naked_b["breakdown"].items()},
                          "attacks": [naked_a["attacks"], naked_b["attacks"]]}
    print(json.dumps(report, indent=1))


