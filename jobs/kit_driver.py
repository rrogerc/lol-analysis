def driver_names(gen_dir=GENERATED_DIR):
    return sorted(f[:-3] for f in os.listdir(gen_dir) if f.endswith(".rs") and f != "mod.rs")


def registry_text(names):
    mods = "".join(f"pub mod {n};\n" for n in names)
    arms = "".join(
        f'        "{n}" => {n}::GenDriver::new(kit, sheet, level, ranks, prestacked)\n'
        f"            .map(|d| Box::new(d) as Box<dyn DriverObj>),\n" for n in names)
    listed = ", ".join(f'"{n}"' for n in names)
    return f'''//! GENERATED by jobs/kit_driver.py (`registry`) from the files in this
//! directory: do not edit. One module per machine-written driver; each
//! exports `pub struct GenDriver` implementing `crate::fight::Driver`.

use crate::dyn_driver::DriverObj;
use crate::fight::Driver;
use crate::kit::Kit;
use crate::num::Ranks;
use crate::sheet::Sheet;

{mods}
pub const NAMES: [&str; {len(names)}] = [{listed}];

#[allow(unused_variables)]
pub fn build(name: &str, kit: &Kit, sheet: &Sheet, level: i64, ranks: Ranks, prestacked: bool)
    -> Result<Box<dyn DriverObj>, String> {{
    match name {{
{arms}        _ => Err(format!("no generated driver for '{{name}}'")),
    }}
}}
'''


def write_registry(gen_dir=GENERATED_DIR):
    names = driver_names(gen_dir)
    with open(os.path.join(gen_dir, "mod.rs"), "w") as f:
        f.write(registry_text(names))
    return names


def is_manaless(slug):
    """The wiki's resource is not Mana: the item pool drops the mana items."""
    return ks.load_sources(slug)["wiki"]["champion"].get("resource") != "Mana"


def cmd_annotate(args):
    """Facts a generated kit takes from the archive rather than from the model:
    "manaless", which the item pool reads (`write` sets it too)."""
    changed = 0
    for name in driver_names():
        path = os.path.join(BASE_DIR, "data", "builds", f"{name}.json")
        if name.endswith("_blind") or not os.path.exists(path):
            continue
        with open(path) as f:
            kit = json.load(f)
        if not kit.get("generated"):
            continue
        manaless = is_manaless(name)
        if bool(kit.get("manaless")) != manaless:
            kit["manaless"] = manaless
            ks.write_json(path, kit)
            changed += 1
    print(f"{changed} kits updated")


def cmd_registry(args):
    names = write_registry()
    print(f"{len(names)} generated drivers: {', '.join(names) or '-'}")


